-- =====================================================================
-- Create the whole Formula Makerspace database from scratch.
--
-- Run this FIRST in Supabase → SQL Editor, then add-missing-columns.sql
-- (access rules), then seed.sql (placeholder data).
--
-- ⚠ It DELETES the tables vehicles, categories, matches, votes, bets and
--   settings if they still exist, including everything in them, and creates
--   them again empty. Only run it when there is nothing to keep.
-- =====================================================================

-- 1. Remove any old versions (cascade also removes links between them)
drop table if exists bets       cascade;
drop table if exists votes      cascade;
drop table if exists settings   cascade;
drop table if exists matches    cascade;
drop table if exists categories cascade;
drop table if exists vehicles   cascade;


-- 2. VEHICLES: one row per car on the grid
create table vehicles (
  id          bigint generated by default as identity primary key,
  name        text not null,
  makerspace  text,                          -- cars with the same text belong to one makerspace
  driver      text,
  powered_by  text,
  reg_nr      text,
  fun_fact    text,
  image       text,                          -- picture URL; empty = dashed "image" box on the site
  broken      boolean not null default false -- set on the admin page
);


-- 3. CATEGORIES: what people can vote on
create table categories (
  id    bigint generated by default as identity primary key,
  name  text not null
);


-- 4. MATCHES: the bracket. 8 matches in round 1 → 4 → 2 → 1 (final)
create table matches (
  id             bigint generated by default as identity primary key,
  round          integer not null,                                    -- 1 = first round … 4 = final
  position       integer not null,                                    -- 1, 2, 3 … within the round
  vehicle_a_id   bigint references vehicles(id) on delete set null,
  vehicle_b_id   bigint references vehicles(id) on delete set null,
  winner_id      bigint references vehicles(id) on delete set null,
  next_match_id  bigint references matches(id)  on delete set null,   -- where the winner goes next
  next_slot      text check (next_slot in ('a', 'b')),                -- into vehicle_a_id or vehicle_b_id there
  starts_at      timestamptz                                          -- for the home-page countdown
);


-- 5. VOTES: one row per vote (no login, so no voter column)
create table votes (
  id           bigint generated by default as identity primary key,
  category_id  bigint not null references categories(id) on delete cascade,
  vehicle_id   bigint not null references vehicles(id)   on delete cascade,
  created_at   timestamptz not null default now()
);


-- 6. BETS: open while taker_name is empty, "on" once someone takes it
create table bets (
  id             bigint generated by default as identity primary key,
  type           text not null,                 -- race_win / tournament_win / breaks / fastest_lap (see js/config.js)
  match_id       bigint references matches(id)  on delete set null,  -- only for race_win bets
  vehicle_id     bigint references vehicles(id) on delete cascade,   -- a bet is on a vehicle …
  makerspace     text,                                               -- … or on a whole makerspace
  creator_name   text not null,
  creator_stake  text not null,
  taker_name     text,
  taker_stake    text,
  created_at     timestamptz not null default now()
);


-- 7. SETTINGS: a single row with event-wide values (edited on the admin page)
create table settings (
  id                   bigint generated by default as identity primary key,
  current_match        bigint references matches(id)  on delete set null,  -- race shown on the home page
  tournament_over      boolean not null default false,
  event_name           text,
  event_place          text,
  laps                 integer,
  best_lap_vehicle_id  bigint references vehicles(id) on delete set null,
  best_lap_time        text                                                -- e.g. 1:12.487
);
